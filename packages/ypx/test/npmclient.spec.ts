/**
 * Npm Client 測試模組
 * Npm Client Test Module
 *
 * 測試使用不同 npm client（npm, yarn, pnpm）執行 ypx 的功能
 * Tests ypx execution with different npm clients (npm, yarn, pnpm)
 *
 * @author bluelovers
 * @since 2026-03-04
 */

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';

import {
	_testCowsayWithClient,
	_verifyCowsayOutput,
	_getExpectedCowsayOutput,
} from './lib/helpers/cowsay-test-helper';
import { say } from 'cowsay';
import { _handleClientsToCheck, IPackageManager } from './lib/whichPackageManager';
import { TEST_TIMEOUT } from './lib/helpers/setup';

/**
 * 測試的 npm client 列表
 * List of npm clients to test
 */
const NPM_CLIENTS: IPackageManager[] = _handleClientsToCheck();

/**
 * Cowsay 測試套件
 * Cowsay test suite
 */
describe('cowsay with different npm clients', () => {

	/**
	 * 測試不使用指定 npm client（使用預設值）
	 * Test without specifying npm client (use default)
	 */
	it('should work with default npm client', { timeout: TEST_TIMEOUT }, async (t) => {
		const result = await _testCowsayWithClient(t, undefined, 'default client');

		/**
		 * 驗證輸出包含 cowsay 格式
		 * Verify output contains cowsay format
		 */
		assert.strictEqual(_verifyCowsayOutput(result.output, 'default client'), true,
			`output should match the cowsay format`);

		/**
		 * 驗證輸出與預期的 cowsay 輸出匹配
		 * Verify output matches expected cowsay output
		 */
		assert.ok(result.output.includes(say({
			text: 'default client',
		})),
			`output should contain the expected cowsay output`);
	});

	/**
	 * 為每個 npm client 建立測試案例
	 * Create test cases for each npm client
	 *
	 * 原為 describe.each（Jest），改以迴圈建立子套件
	 * Was describe.each (Jest); replaced by a loop creating sub-suites
	 */
	for (const npmClient of NPM_CLIENTS)
	{
		describe(`with ${npmClient}`, () => {

			/**
			 * 測試基本 cowsay 功能
			 * Test basic cowsay functionality
			 */
			it(`should run cowsay using ${npmClient}`, { timeout: TEST_TIMEOUT }, async (t) => {
				const testText = `hello from ${npmClient}`;
				const result = await _testCowsayWithClient(t, npmClient, testText);

				/**
				 * 驗證輸出包含預期文字
				 * Verify output contains expected text
				 */
				assert.ok(result.output.includes(`< ${testText} >`),
					`output should contain the expected text`);

				/**
				 * 驗證輸出包含 cowsay 牛圖案
				 * Verify output contains cowsay cow pattern
				 */
				assert.ok(result.output.includes('(oo)\\_______'),
					`output should contain the cowsay cow pattern`);

				/**
				 * 驗證輸出等於以 cowsay 套件產生的預期輸出
				 * Verify output equals the expected output generated by the cowsay package
				 *
				 * 原為 expect(result.output).toMatchSnapshot(matcher)（Jest），
				 * matcher 僅用於比對輸出內容，故改為明確的相等斷言
				 * Was expect(result.output).toMatchSnapshot(matcher) (Jest); the
				 * matcher only compared the output, so it is now an explicit
				 * equality assertion
				 */
				assert.strictEqual(result.output, _getExpectedCowsayOutput(testText),
					`輸出應完全符合預期的 cowsay 輸出`);
			});

			/**
			 * 測試帶有特殊字元的文字
			 * Test text with special characters
			 */
			it(`should handle special characters with ${npmClient}`, { timeout: TEST_TIMEOUT }, async (t) => {
				const testText = 'test 123 !@#$%';
				const result = await _testCowsayWithClient(t, npmClient, testText);

				/**
				 * 驗證 cowsay 輸出格式正確
				 * Verify cowsay output format is correct
				 */
				assert.strictEqual(_verifyCowsayOutput(result.output, testText), true,
					`輸出應符合 cowsay 格式`);
			});

			/**
			 * 測試命令成功執行（結束代碼為 0）
			 * Test command executes successfully (exit code 0)
			 */
			it(`should exit with code 0 using ${npmClient}`, { timeout: TEST_TIMEOUT }, async (t) => {
				const result = await _testCowsayWithClient(t, npmClient, 'success test');

				/**
				 * 驗證結束代碼為 0 或 undefined（成功）
				 * Verify exit code is 0 or undefined (success)
				 */
				assert.ok(!result.exitCode,
					`exit code should be 0 or undefined, got ${result.exitCode}`);
			});

		});
	}

});
